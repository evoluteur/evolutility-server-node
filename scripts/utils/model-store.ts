import { db } from "./query.ts";
import logger from "./logger.ts";
import { schema, diffModels } from "./ddl.ts";
import mm from "./model-manager.ts";
import {
  normalizeModel,
  validateModel,
  type Invalid,
} from "./model-validate.ts";
import type { Model } from "../types.ts";

const T = `${schema}.evol_model`;
const H = `${schema}.evol_model_history`;

// - error w/ an HTTP status (and the list of invalid properties)
export class ModelError extends Error {
  status: number;
  invalids?: Invalid[];
  constructor(message: string, status = 400, invalids?: Invalid[]) {
    super(message);
    this.status = status;
    this.invalids = invalids;
  }
}

export interface SaveResult {
  model: Model;
  version: number;
  sql: string[];
  warnings: string[];
  dryRun: boolean;
}

interface Row {
  id: string;
  model: Model;
  version: number;
  updated_at?: Date;
}

// - load the models from the database (the tables and models are created w/
// - the SQL scripts generated by evolutility-models: "npm run codegen:db")
export async function initModels(): Promise<number> {
  const exists = await db.conn.one<{ t: string | null }>(
    "SELECT to_regclass($1) AS t",
    [`${schema}.evol_model`],
  );
  if (!exists.t) {
    throw new Error(
      `Table ${T} not found. Run the SQL scripts from evolutility-models ("003_create_models" and "004_seed_models").`,
    );
  }
  const rows = await db.conn.any<Row>(`SELECT id, model FROM ${T}`);
  if (!rows.length) {
    logger.logError(
      `No models in ${T}. Run the SQL script "004_seed_models" from evolutility-models.`,
    );
  }
  mm.setModels(rows.map((r) => r.model));
  return rows.length;
}

const withVersion = (r: Row) => ({
  ...r.model,
  _version: r.version,
  _updatedAt: r.updated_at,
});

export async function listModels() {
  const rows = await db.conn.any<Row>(
    `SELECT id, model, version, updated_at FROM ${T} ORDER BY id`,
  );
  return rows.map(withVersion);
}

export async function getStoredModel(id: string) {
  const r = await db.conn.oneOrNone<Row>(
    `SELECT id, model, version, updated_at FROM ${T} WHERE id=$1`,
    [id],
  );
  return r ? withVersion(r) : null;
}

export async function listHistory(id: string) {
  return db.conn.any(
    `SELECT version, saved_at AS "savedAt" FROM ${H} WHERE model_id=$1 ORDER BY version DESC LIMIT 200`,
    [id],
  );
}

export async function getHistoryVersion(id: string, version: number) {
  const r = await db.conn.oneOrNone<{ model: Model; version: number }>(
    `SELECT model, version FROM ${H} WHERE model_id=$1 AND version=$2`,
    [id, version],
  );
  return r ? { ...r.model, _version: r.version } : null;
}

// - other models (to check references to objects)
const otherModels = (id: string) => {
  const others: Record<string, Model> = { ...mm.models };
  delete others[id];
  return others;
};

export interface SaveOptions {
  id?: string; // - id in the url (update)
  version?: number; // - version the user edited (update)
  create?: boolean;
  dryRun?: boolean; // - only check, and list the changes to the DB
}

// - create or update a model, and change the table to match it
export async function saveModel(
  input: unknown,
  opts: SaveOptions,
): Promise<SaveResult> {
  if (!input || typeof input !== "object" || Array.isArray(input)) {
    throw new ModelError("The model must be a JSON object.");
  }
  const model = normalizeModel(input as Model, mm.models);
  if (opts.id && model.id !== opts.id) {
    throw new ModelError(
      `The id of a model can't be changed ("${opts.id}" to "${model.id}").`,
    );
  }

  const result = await db.conn.tx(async (t) => {
    const row = model.id
      ? await t.oneOrNone<Row>(
          `SELECT model, version FROM ${T} WHERE id=$1 FOR UPDATE`,
          [model.id],
        )
      : null;
    if (opts.create && row) {
      throw new ModelError(`Model "${model.id}" already exists.`, 409);
    }
    if (!opts.create && !row) {
      throw new ModelError(`Model not found: "${opts.id}".`, 404);
    }
    if (!opts.create && Number(opts.version) !== row!.version) {
      throw new ModelError(
        `Model "${model.id}" was changed by someone else (now version ${row!.version}). Reload it and try again.`,
        409,
      );
    }

    const { invalids, warnings } = validateModel(model, otherModels(model.id));
    if (invalids.length) {
      throw new ModelError("Invalid model", 400, invalids);
    }
    if (opts.create) {
      const sameTable = Object.values(mm.models).find(
        (m) => (m.table || m.id) === model.table,
      );
      if (sameTable) {
        warnings.push(`Table "${model.table}" is also used by model "${sameTable.id}".`);
      }
    }

    const diff = diffModels(row ? normalizeModel(row.model) : undefined, model);
    if (diff.errors.length) {
      throw new ModelError(diff.errors.join(" "));
    }
    const version = row ? row.version + 1 : 1;
    const res: SaveResult = {
      model,
      version: opts.dryRun ? row?.version || 0 : version,
      sql: diff.sql,
      warnings: [...warnings, ...diff.warnings],
      dryRun: !!opts.dryRun,
    };
    if (opts.dryRun) {
      return res;
    }
    // - DDL is transactional in PostgreSQL: all or nothing w/ the model
    for (const sql of diff.sql) {
      logger.logSQL(sql);
      await t.multi(sql);
    }
    if (row) {
      await t.none(
        `UPDATE ${T} SET model=$2, version=$3, updated_at=timezone('utc', now()) WHERE id=$1`,
        [model.id, model, version],
      );
    } else {
      await t.none(`INSERT INTO ${T}(id, model, version) VALUES($1, $2, $3)`, [
        model.id,
        model,
        version,
      ]);
    }
    await t.none(
      `INSERT INTO ${H}(model_id, version, model) VALUES($1, $2, $3)
       ON CONFLICT (model_id, version) DO UPDATE SET model=EXCLUDED.model, saved_at=timezone('utc', now())`,
      [model.id, version, model],
    );
    return res;
  });

  if (!result.dryRun) {
    // - hot reload: endpoints use the new model right away
    mm.setModel(result.model);
  }
  return result;
}

// - delete a model (its table and data are kept, its history too)
export async function deleteModel(id: string) {
  const usedBy = Object.values(mm.models)
    .filter((m) => m.id !== id)
    .filter(
      (m) =>
        m.fields.some((f) => f.object === id) ||
        (m.collections || []).some((c) => c.object === id),
    )
    .map((m) => m.id);
  if (usedBy.length) {
    throw new ModelError(
      `Model "${id}" is used by: ${usedBy.join(", ")}. Remove these references first.`,
    );
  }
  const r = await db.conn.oneOrNone<{ id: string }>(
    `DELETE FROM ${T} WHERE id=$1 RETURNING id`,
    [id],
  );
  if (!r) {
    throw new ModelError(`Model not found: "${id}".`, 404);
  }
  mm.removeModel(id);
  return { id };
}

export default {
  initModels,
  listModels,
  getStoredModel,
  listHistory,
  getHistoryVersion,
  saveModel,
  deleteModel,
};
